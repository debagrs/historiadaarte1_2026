const local = (nome: string) => `/aula12/artworks/${nome}.jpg`;
const commons = (arquivo: string) =>
  `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(arquivo)}?width=1280`;
const paginaCommons = (arquivo: string) =>
  `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(arquivo.replace(/ /g, '_'))}`;

const FONTE_SLIDES = 'Slides da Profa. Débora Aita Gasparetto, História da Arte (2017)';
const DP = 'Domínio público';

/** Obra reproduzida a partir dos slides da professora. */
const slide = (nome: string, atoNum: number, atoTitulo: string, cena: Partial<Scene12> & { id: string; titulo: string; conteudo: string }): Scene12 => ({
  ato: atoNum,
  tipo: 'image',
  atoTitulo,
  imagemUrl: local(nome),
  imagemAlt: cena.titulo,
  imagemFonte: FONTE_SLIDES,
  imagemLicenca: DP,
  paletaCores: paletas[nome],
  ...cena,
});

/** Obra reproduzida a partir de um arquivo verificado no Wikimedia Commons. */
const acervo = (arquivo: string, atoNum: number, atoTitulo: string, cena: Partial<Scene12> & { id: string; titulo: string; conteudo: string }): Scene12 => ({
  ato: atoNum,
  tipo: 'image',
  atoTitulo,
  imagemUrl: commons(arquivo),
  imagemAlt: cena.titulo,
  imagemFonte: 'Wikimedia Commons',
  imagemLicenca: DP,
  imagemLink: paginaCommons(arquivo),
  ...cena,
});

/** Obra sob direitos autorais: apresentada por descrição e link para o acervo. */
const placa = (atoNum: number, atoTitulo: string, cena: Partial<Scene12> & { id: string; titulo: string; conteudo: string; placa: NonNullable<Scene12['placa']> }): Scene12 => ({
  ato: atoNum,
  tipo: 'image',
  atoTitulo,
  ...cena,
});

